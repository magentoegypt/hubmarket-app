// Writes lib/core/phone/country_names.dart: the English and Arabic name of every region the phone field
// can pick (the regions of `phone_numbers_parser`'s IsoCode enum), from CLDR through Node's built-in ICU
// (`Intl.DisplayNames`), the data browsers print their own country lists from.
//
//   node tool/gen_country_names.mjs
//
// Why not a package's table: country_picker's Arabic list is shifted against its codes (AT reads
// "Australia", KH "Cape Verde"). CLDR is vetted per language and kept current. A few CLDR names are long
// for a list row and are overridden below; a region ICU does not know gets its name from NAMES_BY_HAND.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(readFileSync(join(root, '.dart_tool', 'package_config.json'), 'utf8'));
const pkg = config.packages.find((p) => p.name === 'phone_numbers_parser');
if (!pkg) throw new Error('phone_numbers_parser is not in .dart_tool/package_config.json (run flutter pub get)');
// rootUri is absolute (a pub cache) or relative to .dart_tool/ (a path dependency).
const pkgDir = fileURLToPath(new URL(pkg.rootUri.replace(/\/?$/, '/'), pathToFileURL(join(root, '.dart_tool') + '/')));

const isoSource = readFileSync(join(pkgDir, 'lib', 'src', 'iso_codes', 'iso_code.dart'), 'utf8');
const enumStart = isoSource.indexOf('enum IsoCode');
const enumBody = isoSource.slice(enumStart, isoSource.indexOf('}', enumStart));
const codes = [...enumBody.matchAll(/^\s+([A-Z]{2})[,;]\s*$/gm)].map((m) => m[1]);
if (codes.length < 200) throw new Error(`only ${codes.length} region codes found`);

// Long CLDR names shortened for a list row.
const OVERRIDES = {
  en: {
    HK: 'Hong Kong',
    MO: 'Macao',
    CD: 'Congo (DRC)',
    CG: 'Congo (Republic)',
    MM: 'Myanmar',
    PS: 'Palestine',
    FK: 'Falkland Islands',
  },
  ar: {
    HK: 'هونغ كونغ',
    MO: 'ماكاو',
    CD: 'الكونغو الديمقراطية',
    CG: 'جمهورية الكونغو',
    PS: 'فلسطين',
  },
};
// Regions CLDR has no name for.
const NAMES_BY_HAND = {
  AC: { en: 'Ascension Island', ar: 'جزيرة أسنشين' },
  TA: { en: 'Tristan da Cunha', ar: 'تريستان دا كونا' },
};

const names = { en: new Intl.DisplayNames(['en'], { type: 'region' }), ar: new Intl.DisplayNames(['ar'], { type: 'region' }) };
const out = { en: {}, ar: {} };
for (const code of codes) {
  for (const lang of ['en', 'ar']) {
    let name = OVERRIDES[lang][code] ?? NAMES_BY_HAND[code]?.[lang] ?? names[lang].of(code);
    if (!name || name === code) throw new Error(`no ${lang} name for ${code}: add it to NAMES_BY_HAND`);
    if (name.includes('$')) throw new Error(`${code}: "$" would need escaping in Dart`);
    out[lang][code] = name;
  }
}

const dart = (map) =>
  Object.entries(map)
    .map(([code, name]) => `  '${code}': ${JSON.stringify(name)},`)
    .join('\n');

const text = `// GENERATED by tool/gen_country_names.mjs: do not edit by hand.
//
// The name of each region the phone field can pick, from CLDR (Node's ICU). Run
// \`node tool/gen_country_names.mjs\` again to refresh it.

/// English names, by ISO 3166 region code (the codes of \`IsoCode\`).
const Map<String, String> kCountryNamesEn = {
${dart(out.en)}
};

/// Arabic names, by ISO 3166 region code.
const Map<String, String> kCountryNamesAr = {
${dart(out.ar)}
};
`;
writeFileSync(join(root, 'lib', 'core', 'phone', 'country_names.dart'), text, 'utf8');
console.log(`wrote ${codes.length} regions`);
